'use strict';
const fs = require('node:fs'), assert = require('node:assert/strict');
exports.run = async ({ page, app, phone:live, file, original:source, state }) => {
  const settled = () => page.waitForFunction(() => !undoBusy && !sourceRequests && !panelTasks);
  const wait = async predicate => { for (let i = 0; i < 160; i++) { if (await predicate()) return; await new Promise(resolve => setTimeout(resolve, 50)); } throw Error('Svelte reparenting did not settle: '+JSON.stringify({source:fs.readFileSync(file,'utf8'),state:await page.evaluate(()=>({toasts:document.querySelector('#toasts')?.textContent,selected:sel?.info?.structure,dragging:document.querySelector('.layer-drop')?.outerHTML}))})); };
  const row = name => page.getByRole('treeitem', { name, exact: true });
  const mover = app.locator('[aria-label=Mover]');
  const undo = async () => { await page.getByRole('button', { name: 'Undo', exact: true }).click(); await settled(); await state(); };
  await page.getByRole('button', { name: 'Lock div · Neighbor', exact: true }).click();
  await row('div · Mover').click(); await settled();
  const padding = page.getByLabel('Padding (CSS)', { exact: true }); await padding.fill('17px'); await padding.press('Tab'); await settled();
  const styled = fs.readFileSync(file, 'utf8'), originalId = await mover.getAttribute('data-rt');
  const action = page.locator('[data-design-action=reparentElement]');
  if (!await action.isVisible()) await page.getByText('Layer actions', { exact: true }).click();
  await action.click();
  const destination = await app.locator('#move-to').getAttribute('data-rt');
  await page.getByLabel('Destination container', { exact: true }).selectOption(destination);
  await page.getByRole('button', { name: 'Move layer', exact: true }).click(); await settled();
  const moved = async () => await app.locator('#move-to > [aria-label=Mover]').count() === 1 && await live.locator('#move-to > [aria-label=Mover]').count() === 1;
  await wait(moved);
  assert.notEqual(await mover.getAttribute('data-rt'), originalId);
  assert.equal(await mover.evaluate(element => getComputedStyle(element).paddingTop), '17px');
  await page.getByRole('button', { name: 'Unlock div · Neighbor', exact: true }).waitFor();
  await state();await page.screenshot({path:'/tmp/retouch-svelte-reparent-'+(process.env.RT_E2E_BROWSER||'chromium')+'.png'});
  const movedSource = fs.readFileSync(file, 'utf8');
  await undo(); assert.equal(fs.readFileSync(file, 'utf8'), styled);
  await page.getByRole('button', { name: 'Redo', exact: true }).click(); await settled(); await wait(moved);
  assert.equal(fs.readFileSync(file, 'utf8'), movedSource);
  await undo(); assert.equal(fs.readFileSync(file, 'utf8'), styled);
  await page.getByText('Layer actions', { exact: true }).click();
  await row('div · Mover').click(); await settled();
  await wait(async()=>await row('div · Mover').getAttribute('aria-selected')==='true' && await page.locator('#layersPanel').getAttribute('aria-busy')!=='true');
  await row('div · Mover').dragTo(row('section · move-to')); await settled(); await wait(moved);
  assert.equal(await mover.evaluate(element => getComputedStyle(element).paddingTop), '17px');
  await page.getByRole('button', { name: 'Unlock div · Neighbor', exact: true }).waitFor();
  await undo(); assert.equal(fs.readFileSync(file, 'utf8'), styled);
  await undo(); assert.equal(fs.readFileSync(file, 'utf8'), source);
  await state();
  await page.getByRole('button', { name: 'Unlock div · Neighbor', exact: true }).click();
  await row('h1 · Hello Svelte').click(); await settled();
  console.log('SVELTE MOVE-INTO PICKER, TREE DRAG, STYLE/LOCK OWNERSHIP AND EXACT HISTORY PASS');
};
